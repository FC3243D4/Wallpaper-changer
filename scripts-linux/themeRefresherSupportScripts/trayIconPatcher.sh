fix_onedrivegui_permissions() {
    fix_system_dir_permissions "$ONEDRIVEGUI_IMAGES_DIR" "onedrivegui"
}

patch_onedrivegui_tray() {
    command -v onedrivegui >/dev/null 2>&1 || return 0
    [ -d "$ONEDRIVEGUI_IMAGES_DIR" ] || {
        echo "  onedrivegui: $ONEDRIVEGUI_IMAGES_DIR not found (package layout may have changed)"
        return 1
    }

    if [ "$LIST_ONLY" -eq 1 ]; then
        echo "onedrivegui: custom SVG replacements:"
        for name in "${!ONEDRIVEGUI_SVG_OVERRIDES[@]}"; do
            IFS=':' read -r icon_name target <<< "${ONEDRIVEGUI_SVG_OVERRIDES[$name]}"
            [ "$target" = "accent" ] && target="$accent"
            printf '  %-28s -> %s_base_icon.svg (%s)\n' "$name" "$icon_name" "$target"
        done
        echo "onedrivegui: plain recolor (existing vendor art):"
        for name in "${!ONEDRIVEGUI_COLORIZE_ONLY[@]}"; do
            local target="${ONEDRIVEGUI_COLORIZE_ONLY[$name]}"
            [ "$target" = "accent" ] && target="$accent"
            printf '  %-28s -> %s\n' "$name" "$target"
        done
        echo "  (left alone: icons8-green-circle-48.png, icons8-red-circle-48.png, and"
        echo "   in-window UI icons like account/folder/gear/play/pause/quit)"
        return 0
    fi

    local tool=""
    command -v magick >/dev/null 2>&1 && tool="magick"
    [ -z "$tool" ] && command -v convert >/dev/null 2>&1 && tool="convert"
    if [ -z "$tool" ]; then
        echo "  onedrivegui: ImageMagick not found, cannot recolor icons"
        return 1
    fi
    command -v rsvg-convert >/dev/null 2>&1 || {
        echo "  onedrivegui: rsvg-convert not found, cannot rasterize custom SVGs"
        return 1
    }

    fix_onedrivegui_permissions || return 1

    local patched=0 skipped=0

    # -- custom SVG replacements --
    for name in "${!ONEDRIVEGUI_SVG_OVERRIDES[@]}"; do
        local f="$ONEDRIVEGUI_IMAGES_DIR/$name"
        [ -f "$f" ] || { echo "  onedrivegui: vendor file $name not found, skipping"; continue; }

        IFS=':' read -r icon_name target <<< "${ONEDRIVEGUI_SVG_OVERRIDES[$name]}"
        [ "$target" = "accent" ] && target="$accent"

        local src_svg="$ICONS/${icon_name}_base_icon.svg"
        if [ ! -f "$src_svg" ]; then
            echo "  onedrivegui: $src_svg not found — add it, or drop this override for $name"
            skipped=$((skipped + 1))
            continue
        fi

        local backup="${f}.orig"
        [ -f "$backup" ] || cp "$f" "$backup"

        # Match the vendor icon's own pixel size so it doesn't look
        # mismatched next to the icons we're leaving alone.
        local dims
        if command -v identify >/dev/null 2>&1; then
            dims=$(identify -format "%wx%h" "$backup" 2>/dev/null)
        else
            dims=$("$tool" identify -format "%wx%h" "$backup" 2>/dev/null)
        fi
        local w="${dims%x*}" h="${dims#*x}"
        [ -z "$w" ] && w=80
        [ -z "$h" ] && h=80

        local tmp_svg tmp_png
        tmp_svg=$(mktemp --suffix=.svg)
        tmp_png=$(mktemp --suffix=.png)
        sed "s/currentColor/$target/g" "$src_svg" > "$tmp_svg"
        rsvg-convert -w "$w" -h "$h" "$tmp_svg" -o "$tmp_png"
        cp "$tmp_png" "$f"
        rm -f "$tmp_svg" "$tmp_png"
        patched=$((patched + 1))
        echo "  $name replaced with ${icon_name}_base_icon.svg ($target)"
    done

    # -- plain recolor of remaining vendor art --
    for name in "${!ONEDRIVEGUI_COLORIZE_ONLY[@]}"; do
        local f="$ONEDRIVEGUI_IMAGES_DIR/$name"
        [ -f "$f" ] || { echo "  onedrivegui: vendor file $name not found, skipping"; continue; }

        local target="${ONEDRIVEGUI_COLORIZE_ONLY[$name]}"
        [ "$target" = "accent" ] && target="$accent"

        local backup="${f}.orig"
        [ -f "$backup" ] || cp "$f" "$backup"

        "$tool" "$backup" -fill "$target" -colorize 100% "$f"
        patched=$((patched + 1))
    done

    echo "OneDriveGUI tray icons patched ($patched patched, $skipped skipped)"
    echo "  (originals preserved as *.png.orig next to each file)"
}

# ===========================================================================
# 4. Vesktop — confirmed via `find ~/.config/vesktop` that the real,
#    currently-shipping (v1.6.0+) "User Assets" feature stores its picked
#    tray icon at a literal, extensionless file:
#
#        ~/.config/vesktop/userAssets/tray
#        ~/.config/vesktop/userAssets/trayUnread   (badge overlay variant)
#
#    copied there once when you use the "Customize" button under
#    Settings -> User Assets -> Tray. `trayIconPath` in settings.json
#    LOOKS like the right hook (it's exactly what the early, never-merged
#    2024 draft PR #576 used) but is dead: the actual shipped feature
#    (#1179) is a full rewrite that doesn't read it at all. Don't be
#    fooled by it again — the file below is the one that matters.
#
#    Electron re-reads this file from disk on every tray repaint, same
#    reasoning as before — no restart needed *if* Vesktop is already
#    running past its initial load, though a long-idle instance since
#    boot still won't repaint until something (unread count, mute, or a
#    fresh launch) triggers one. See VESKTOP_TRAY_RESTART below.
# ===========================================================================

patch_vesktop_tray() {
    command -v vesktop >/dev/null 2>&1 || return 0

    local user_assets="$HOME/.config/vesktop/userAssets"

    # Don't create userAssets/ ourselves if Vesktop has never initialized
    # it — writing files there before Vesktop knows about custom assets
    # at all may not be picked up. Ask once via the UI (Customize ->
    # pick any file, for both Tray and Tray Unread) so Vesktop creates
    # its own tray/trayUnread files, then this script just keeps
    # overwriting them from then on.
    [ -d "$user_assets" ] || {
        echo "  vesktop: $user_assets doesn't exist yet — open Vesktop's"
        echo "  Settings -> User Assets -> Tray/Tray Unread -> Customize"
        echo "  and pick any image once for each, then re-run this script."
        return 1
    }

    command -v rsvg-convert >/dev/null 2>&1 || {
        echo "  vesktop: rsvg-convert not found, cannot rasterize"; return 1
    }

    local patched=0

    # -- plain tray icon --
    local svg
    svg=$(resolve_themed_svg "vesktop") || svg=$(resolve_themed_svg "discord") || {
        echo "  vesktop: no themed base icon found for tray, skipping"
    }
    if [ -n "$svg" ]; then
        local target="$user_assets/tray"
        if [ "$LIST_ONLY" -eq 1 ]; then
            echo "vesktop: would overwrite $target"
        else
            rsvg-convert -w 64 -h 64 "$svg" -o "$target" \
                && { echo "Vesktop tray icon patched in place ($target)"; patched=$((patched + 1)); }
        fi
    fi

    # -- unread-badge variant — separate base icon, since the badge is
    # baked into the artwork itself rather than composited by Vesktop
    # (unlike Ferdium/OneDriveGUI, there's no separate dot overlay step
    # here — whatever discord-unread_base_icon.svg draws is exactly what
    # shows in the tray). --
    local svg_unread
    svg_unread=$(resolve_themed_svg "discord-unread") || {
        echo "  vesktop: discord-unread_base_icon.svg not found, skipping trayUnread"
    }
    if [ -n "$svg_unread" ]; then
        local target_unread="$user_assets/trayUnread"
        if [ "$LIST_ONLY" -eq 1 ]; then
            echo "vesktop: would overwrite $target_unread"
        else
            rsvg-convert -w 64 -h 64 "$svg_unread" -o "$target_unread" \
                && { echo "Vesktop trayUnread icon patched in place ($target_unread)"; patched=$((patched + 1)); }
        fi
    fi

    [ "$LIST_ONLY" -eq 1 ] && return 0
    [ "$patched" -gt 0 ]
}

# ===========================================================================
# 5. YTMDesktop (ytmdesktop/ytmdesktop) — confirmed via source
#    (src/main/index.ts, trayIconFileName()/getTrayIconPath()): on Linux the
#    tray icon is one of two fixed files selected by the
#    "appearance.trayIconStyle" setting (Auto follows the OS's own
#    light/dark GTK theme via nativeTheme.shouldUseDarkColors — nothing to
#    do with the wallpaper accent):
#
#        ytmd_white.png   (style=White, or Auto+dark)
#        ytmd_black.png   (style=Black, or Auto+light)
#
#    Both ship as an electron-forge extraResource — real loose files next
#    to the app, not packed inside app.asar — so overwriting them in place
#    is enough, no unpacking required. AUR installs these under
#    /opt/ytmdesktop/resources (root-owned, confirmed against AUR package
#    comments referencing /opt/ytmdesktop/chrome-sandbox); a couple of
#    alternate layouts are tried too in case yours differs. Since Auto is
#    the default and just alternates between these two files depending on
#    system theme, both get the same accent icon so it looks right either
#    way rather than trying to keep a literal white/black pair.
#
#    getTrayIconPath() is only ever re-read from disk when setTrayIcon()
#    runs (a nativeTheme 'updated' event, or trayIconStyle actually
#    changing) — never on a timer, and never just because the file on disk
#    changed. Restarting the app would force it, but interrupts playback,
#    so instead this edits trayIconStyle in YTMDesktop's own config.json.
#
#    IMPORTANT, confirmed by reading the actual `conf` package source
#    (node_modules/conf/dist/source/index.js, _watch()): on Linux/macOS it
#    does NOT use inotify. It uses fs.watchFile — polling every ~5s —
#    wrapped in its own 5000ms trailing debounce, so an external edit can
#    take up to ~10s to be noticed at all. Worse, _handleChange() only
#    compares the value from *before* the edit(s) to whatever it reads on
#    the *next* poll — it never sees anything in between. A fast
#    toggle-and-revert (write A, sleep briefly, write back the original)
#    lands back on the original value before that first poll ever fires,
#    so the "before" and "after" it observes are identical and
#    setTrayIcon() never gets called — this is exactly why an earlier
#    version of this function silently did nothing.
#
#    Since both ytmd_white.png and ytmd_black.png now hold the *same*
#    accent icon, which one trayIconStyle points at no longer changes
#    anything visually — so instead of toggling and reverting, this makes
#    one real, permanent-feeling write to a different value (guaranteed to
#    be noticed on the next poll, nothing to race against), then reverts
#    it in a detached background job after enough time has passed for that
#    first change to land — purely cosmetic, so your Settings page still
#    shows your real trayIconStyle choice afterward.
# ===========================================================================

patch_ytmdesktop_tray() {
    local resource_dir=""
    local candidates=(
        "/opt/ytmdesktop/resources"
        "/opt/YouTube Music Desktop App/resources"
        "/usr/lib/ytmdesktop/resources"
    )
    local d
    for d in "${candidates[@]}"; do
        if [ -f "$d/ytmd_white.png" ] && [ -f "$d/ytmd_black.png" ]; then
            resource_dir="$d"
            break
        fi
    done
    [ -n "$resource_dir" ] || {
        echo "  ytmdesktop: ytmd_white.png/ytmd_black.png not found under any of:"
        printf '    %s\n' "${candidates[@]}"
        echo "  (package layout may differ — find them with:"
        echo "   find / -name 'ytmd_white.png' 2>/dev/null)"
        return 1
    }

    local svg
    svg=$(resolve_themed_svg "music") || { echo "  ytmdesktop: music_base_icon.svg not found, skipping tray"; return 1; }

    local targets=("$resource_dir/ytmd_white.png" "$resource_dir/ytmd_black.png")

    if [ "$LIST_ONLY" -eq 1 ]; then
        echo "ytmdesktop: would overwrite:"
        printf '  %s\n' "${targets[@]}"
        return 0
    fi

    command -v rsvg-convert >/dev/null 2>&1 || {
        echo "  ytmdesktop: rsvg-convert not found, cannot rasterize"; return 1
    }
    fix_system_dir_permissions "$resource_dir" "ytmdesktop" || return 1

    local patched=0
    local f
    for f in "${targets[@]}"; do
        local backup="${f}.orig"
        [ -f "$backup" ] || cp "$f" "$backup"
        # Match the original 512x512 canvas so the tray-side downscale
        # behaves the same as upstream's own icon.
        rsvg-convert -w 512 -h 512 "$svg" -o "$f" && patched=$((patched + 1))
    done
    echo "YTMDesktop tray icons patched in place ($patched/${#targets[@]}, $resource_dir)"

    [ "$patched" -gt 0 ] && ytmdesktop_force_reload
}

# Makes one durable change to trayIconStyle in YTMDesktop's own config.json
# so its `conf` store — polling via fs.watchFile on Linux, see the long
# comment above — actually notices it and calls setTrayIcon() itself,
# re-reading the PNGs we just overwrote. Values: Auto=0, White=1, Black=2
# (src/shared/store/schema.ts). Schedules a delayed, detached revert back
# to your real setting — cosmetic only, since ytmd_white.png and
# ytmd_black.png are now identical, so which one gets selected doesn't
# change what's actually drawn in the tray.
ytmdesktop_force_reload() {
    { pgrep -x youtube-music-desktop-app >/dev/null 2>&1 || pgrep -f ytmdesktop >/dev/null 2>&1; } || {
        echo "  ytmdesktop: not currently running, nothing to notify"
        return 0
    }
    command -v jq >/dev/null 2>&1 || {
        echo "  ytmdesktop: jq not found, can't trigger a live tray refresh"
        echo "  (new icons will show next time YTMDesktop starts)"
        return 1
    }

    local cfg="$HOME/.config/YouTube Music Desktop App/config.json"
    [ -f "$cfg" ] || {
        echo "  ytmdesktop: config.json not found at $cfg, can't trigger a live refresh"
        return 1
    }

    local current other tmp
    current=$(jq -r '.appearance.trayIconStyle // 0' "$cfg")
    other=$(( (current + 1) % 3 ))

    tmp=$(mktemp)
    jq ".appearance.trayIconStyle = $other" "$cfg" > "$tmp" && mv "$tmp" "$cfg"
    echo "  ytmdesktop: set trayIconStyle $current -> $other to force a live repaint"
    echo "  (conf polls the file on Linux — can take up to ~10s to actually redraw)"

    # Detached: this script's own run finishes long before the revert
    # fires, no need to make the theme refresh wait ~10+ more seconds on
    # a cosmetic settings-value cleanup.
    (
        sleep 12
        tmp2=$(mktemp)
        jq ".appearance.trayIconStyle = $current" "$cfg" > "$tmp2" 2>/dev/null && mv "$tmp2" "$cfg"
    ) >/dev/null 2>&1 &
    disown
}

