    svg=$(resolve_themed_svg "localsend") || { echo "  localsend: no themed base icon found, skipping tray"; return 1; }

    local names=(logo-32.png logo-32-black.png logo-32-white.png)

    if [ "$LIST_ONLY" -eq 1 ]; then
