#Requires -Version 7.0
<#
.SYNOPSIS
  Patches userChrome/userContent CSS of every profile of Firefox, Zen or Thunderbird/Betterbird.

.DESCRIPTION
  Port of FirefoxPatcher.sh, ZenPatcher.sh and ThunderbirdPatcher.sh (same CSS).
  Differences on purpose:
    * an existing userChrome.css / userContent.css that this script did not
      write is backed up once as *.wc-bak before being replaced;
    * the stylesheet pref goes into user.js instead of prefs.js, because the
      browser rewrites prefs.js on exit and would drop the line if it is
      still running.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$Color,
    [Parameter(Mandatory)][ValidateSet('Firefox', 'Zen', 'Thunderbird')][string]$App
)

$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot '..\..\lib\WallpaperChanger.Common.psm1') -DisableNameChecking

$accent = '#' + (ConvertTo-HexColor $Color)

$roots = switch ($App) {
    'Firefox' { @(Join-Path $env:APPDATA 'Mozilla\Firefox') }
    'Zen' { @(Join-Path $env:APPDATA 'zen') }
    'Thunderbird' { @((Join-Path $env:APPDATA 'Thunderbird'), (Join-Path $env:APPDATA 'Betterbird')) }
}

$header = '/* Generated by ThemeRefresher */'
if ($App -eq 'Thunderbird') {
    $chrome = @"
$header
:root {
    --lwt-accent-color: $accent !important;
    --toolbar-field-focus-border-color: $accent !important;
    --toolbar-field-color: #fcfcfc !important;
    --toolbar-field-focus-color: #fcfcfc !important;
    --toolbar-color: #fcfcfc !important;
    --sidebar-highlight-background-color: $accent !important;
    --selected-item-color: $accent !important;
}

/* folder pane selected folder */
#folderTree tr.selected,
treechildren::-moz-tree-row(selected) {
    background-color: $accent !important;
}

/* thread pane - table view */
tr[is="thread-row"].selected {
    background-color: $accent !important;
    color: #fcfcfc !important;
}

/* thread pane - card view */
tr[is="thread-card"].selected .card-container {
    background-color: $accent !important;
    color: #fcfcfc !important;
}

::selection { background-color: $accent !important; color: #ffffff !important; }
"@
}
else {
    $chrome = @"
$header
:root {
    --lwt-accent-color: $accent !important;
    --toolbar-field-focus-border-color: $accent !important;
    --toolbar-field-color: #fcfcfc !important;
    --toolbar-field-focus-color: #fcfcfc !important;
    --toolbar-color: #fcfcfc !important;
    --urlbar-box-text-color: #fcfcfc !important;
}
#urlbar-input { color: #fcfcfc !important; }
::selection { background-color: $accent !important; color: #ffffff !important; }
"@
}
$content = "$header`n::selection { background-color: $accent !important; color: #ffffff !important; }`n"

function Write-GeneratedCss {
    param([string]$Path, [string]$Css)
    if ((Test-Path -LiteralPath $Path) -and -not ((Get-Content -LiteralPath $Path -TotalCount 1) -ceq $header)) {
        Write-WcFile -Path $Path -Content $Css -Backup      # first time: keep the user's own file
    }
    else { Write-WcFile -Path $Path -Content $Css }
}

$patched = 0
foreach ($root in $roots) {
    foreach ($profileDir in (Get-MozillaProfileDirs -Root $root)) {
        $chromeDir = Join-Path $profileDir 'chrome'
        New-Item -ItemType Directory -Path $chromeDir -Force | Out-Null
        Write-GeneratedCss -Path (Join-Path $chromeDir 'userChrome.css') -Css ($chrome + "`n")
        Write-GeneratedCss -Path (Join-Path $chromeDir 'userContent.css') -Css $content

        $userJs = Join-Path $profileDir 'user.js'
        $pref = 'user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);'
        $existing = if (Test-Path -LiteralPath $userJs) { Get-Content -LiteralPath $userJs -Raw } else { '' }
        if ($existing -notmatch 'toolkit\.legacyUserProfileCustomizations\.stylesheets') {
            Write-WcFile -Path $userJs -Content ($existing.TrimEnd() + "`n$pref`n").TrimStart()
        }
        Write-Output "$App profile patched: $profileDir"
        $patched++
    }
}
if ($patched -eq 0) { Write-Output "No $App profiles found (checked: $($roots -join ', '))" }
else { Write-Output "Restart $App for the changes to fully apply." }
